test("npm lifecycle scripts fail closed", () => {
  const root = fixture();
  npmFiles(root, {
    name: "fixture", version: "1.0.0", private: true,
    scripts: { test: "node --test", postinstall: "node surprise.js" },
    dependencies: { exact: "1.2.3" },
  }, {
    "": { name: "fixture", version: "1.0.0", dependencies: { exact: "1.2.3" } },
    "node_modules/exact": {
      version: "1.2.3", resolved: "https://registry.npmjs.org/exact/-/exact-1.2.3.tgz",
      integrity: INTEGRITY, hasInstallScript: true,
    },
  });
  const errors = problems(root).join("\n");
  assert.match(errors, /lifecycle script postinstall/);
  assert.match(errors, /node_modules\/exact has an unaudited lifecycle install script/);
  assert.doesNotMatch(errors, /lifecycle script test/);
});

