"use strict";

const assert = require("node:assert/strict");
const fs = require("node:fs");
const os = require("node:os");
const path = require("node:path");
const { test } = require("node:test");

const { audit } = require("./check_deps.js");

const INTEGRITY = `sha512-${Buffer.alloc(64).toString("base64")}`;

// The audited crates, which the fixture must carry in full: `check_deps.js`
// asserts each one is present, so a fixture short of the set reports missing
// crates on top of whatever the test came to look at. This constant exists so
// that adding one to the audit is a single edit here rather than three, which
// is what went wrong when v2-ui-08 added `learn-core` and this file stayed red.
const MEMBERS = ["fx", "sim", "policy", "learn-core", "learn", "lab", "web"];
const membersLine = (names = MEMBERS) =>
  `members = [${names.map((name) => `"crates/${name}"`).join(", ")}]`;

function write(root, rel, body) {
  const file = path.join(root, rel);
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, body);
}

function fixture() {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), "auto-rpg-deps-"));
  write(root, "Cargo.toml", `[workspace]\nresolver = "2"\n${membersLine()}\n`);
  write(root, "Cargo.lock", "# This file is automatically @generated by Cargo.\nversion = 4\n");
  for (const name of MEMBERS) {
    write(root, `crates/${name}/Cargo.toml`, `[package]\nname = "${name}"\nversion = "0.1.0"\nedition = "2021"\n`);
    write(root, `crates/${name}/src/lib.rs`, "");
  }
  write(root, "tools/toolchain.json", JSON.stringify({
    node: "22.12.0",
    npm: "10.9.0",
    manifests: [
      "Cargo.toml",
      "Cargo.lock",
      ...MEMBERS.map((name) => `crates/${name}/Cargo.toml`),
      "tools/toolchain.json",
    ],
  }));
  return root;
}

function problems(root) {
  try {
    return audit(root);
  } finally {
    fs.rmSync(root, { recursive: true, force: true });
  }
}

function npmFiles(root, manifest, packages) {
  write(root, "package.json", JSON.stringify(manifest));
  write(root, "package-lock.json", JSON.stringify({
    name: manifest.name,
    version: manifest.version,
    lockfileVersion: 3,
    requires: true,
    packages,
  }));
  const toolchainFile = path.join(root, "tools", "toolchain.json");
  const toolchain = JSON.parse(fs.readFileSync(toolchainFile, "utf8"));
  toolchain.manifests.push("package.json", "package-lock.json");
  write(root, "tools/toolchain.json", JSON.stringify(toolchain));
}

test("deterministic crates reject normal build and dev registry dependencies", () => {
  const root = fixture();
  write(root, "crates/fx/Cargo.toml", [
    '[package]', 'name = "fx"', 'version = "0.1.0"', 'edition = "2021"',
    '[dependencies]', 'normal_dep = "=1.0.0"',
    '[build-dependencies]', 'build_dep = "=1.0.0"',
    '[dev-dependencies]', 'dev_dep = "=1.0.0"', '',
  ].join("\n"));
  const errors = problems(root).join("\n");
  assert.match(errors, /fx -> normal_dep \(normal, registry\)/);
  assert.match(errors, /fx -> build_dep \(build, registry\)/);
  assert.match(errors, /fx -> dev_dep \(dev, registry\)/);
});

