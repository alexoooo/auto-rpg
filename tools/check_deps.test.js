test("workspace inheritance cannot hide a source", () => {
  const root = fixture();
  write(root, "Cargo.toml", [
    '[workspace]', 'resolver = "2"', membersLine(),
    '[workspace.dependencies]', 'hidden = "=1.0.0"', '',
  ].join("\n"));
  write(root, "crates/sim/Cargo.toml", [
    '[package]', 'name = "sim"', 'version = "0.1.0"', 'edition = "2021"',
    '[dependencies]', 'hidden = { workspace = true }', '',
  ].join("\n"));
  assert.match(problems(root).join("\n"), /sim -> hidden \(normal, registry\)/);
});

test("every workspace member is audited and not only the core", () => {
  // The hole a review found: the walk seeded from a five-name set, so `web` and
  // `lab` -- neither in it nor reachable from anything in it -- could declare a
  // registry dependency that compiled into web.wasm while this audit printed
  // "passed". Asserted over every member, because "which ones are seeded" is
  // the thing that was wrong and naming two of them would leave an eighth crate
  // in the same position.
  const root = fixture();
  for (const name of MEMBERS) {
    write(root, `crates/${name}/Cargo.toml`, [
      '[package]', `name = "${name}"`, 'version = "0.1.0"', 'edition = "2021"',
      '[dependencies]', 'sha2 = "=0.10.8"', '',
    ].join("\n"));
  }
  const errors = problems(root).join("\n");
  for (const name of MEMBERS) {
    assert.match(errors, new RegExp(`${name} -> sha2 \\(normal, registry\\)`), `${name} was not audited`);
  }
});

test("deterministic crates reject custom build targets", () => {
  const root = fixture();
  write(root, "crates/fx/build.rs", "fn main() {}\n");
  assert.match(
    problems(root).join("\n"),
    /audited dependency path fx uses forbidden custom-build target build-script-build/,
  );
});

test("deterministic workspace packages cannot escape through their own realpath", () => {
  const root = fixture();
  const outside = fs.mkdtempSync(path.join(os.tmpdir(), "auto-rpg-outside-fx-"));
  write(outside, "Cargo.toml", '[package]\nname = "fx"\nversion = "0.1.0"\nedition = "2021"\n');
  write(outside, "src/lib.rs", "");
  const member = path.relative(root, outside).replaceAll("\\", "/");
  const rest = MEMBERS.filter((name) => name !== "fx").map((name) => `"crates/${name}"`);
  write(root, "Cargo.toml", [
    '[workspace]', 'resolver = "2"',
    `members = ["${member}", ${rest.join(", ")}]`, '',
  ].join("\n"));
  let errors;
  try {
    errors = audit(root).join("\n");
  } finally {
    fs.rmSync(root, { recursive: true, force: true });
    fs.rmSync(outside, { recursive: true, force: true });
  }
  assert.match(
    errors,
    /workspace package fx leaves the repository after realpath resolution|is not hierarchically below the workspace root/,
  );
});

test("npm manifest and lock must agree", () => {
  const root = fixture();
  npmFiles(root, {
    name: "fixture", version: "1.0.0", private: true,
    dependencies: { exact: "1.2.3", ranged: "^2.0.0" },
  }, {
    "": { name: "fixture", version: "1.0.0", dependencies: { exact: "1.2.4", ranged: "^2.0.0" } },
    "node_modules/exact": { version: "1.2.4", resolved: "https://registry.npmjs.org/exact/-/exact-1.2.4.tgz" },
  });
  const errors = problems(root).join("\n");
  assert.match(errors, /ranged must be an exact version/);
  assert.match(errors, /exact.*manifest requests "1\.2\.3"/);
  assert.match(errors, /node_modules\/exact resolved "1\.2\.4"/);
  assert.match(errors, /node_modules\/ranged/);
  assert.match(errors, /no valid lockfile integrity/);
});

test("every_transitive_lock_edge_resolves_through_the_npm_ancestor_chain", () => {
  const root = fixture();
  npmFiles(root, {
    name: "fixture", version: "1.0.0", private: true,
    dependencies: { parent: "1.0.0" },
  }, {
    "": { name: "fixture", version: "1.0.0", dependencies: { parent: "1.0.0" } },
    "node_modules/parent": {
      version: "1.0.0", resolved: "https://registry.npmjs.org/parent/-/parent-1.0.0.tgz",
      integrity: INTEGRITY, dependencies: { deleted: "2.0.0" },
    },
  });
  assert.match(
    problems(root).join("\n"),
    /node_modules\/parent\.dependencies\.deleted has no lock entry in its npm ancestor chain/,
  );
});

test("orphan lock records and lifecycle exceptions fail closed", () => {
  const root = fixture();
  npmFiles(root, { name: "fixture", version: "1.0.0", private: true }, {
    "": { name: "fixture", version: "1.0.0" },
    "node_modules/fsevents": {
      version: "2.3.3", resolved: "https://registry.npmjs.org/fsevents/-/fsevents-2.3.3.tgz",
      integrity: INTEGRITY, hasInstallScript: true, optional: true, os: ["darwin"],
    },
  });
  const errors = problems(root).join("\n");
  assert.match(errors, /node_modules\/fsevents is unreachable from the root manifest/);
  assert.match(errors, /reachable transitive false/);
});

