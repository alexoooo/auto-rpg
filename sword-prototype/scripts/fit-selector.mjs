// Fit the selector's table from tournament rows and write it out as the checked-in module
// `src/golem/selector-table.ts`. Session 09 of the style set.
//
//   node scripts/fit-selector.mjs --in a.jsonl[,b.jsonl] [--out src/golem/selector-table.ts]
//                                 [--shrink 32] [--minds golem-fencer,...] [--report]
//
// The rows already carry everything the fit needs and have since Session 07 of the matchup set:
// `arm` on each side is the class that side read off its own first view, so a row is one bout of
// one candidate in one cell, and `winner` is the point. Nothing here re-runs a bout.
//
// `--report` prints the cell table -- bouts, the marginal winner, the cell's own winner and the
// two shrunk scores -- which is what goes in the measurements entry. Read it before believing
// the module: a cell whose winner beats the marginal by 0.2 on nine bouts is the winner's curse
// with a name, and the margin rule in `src/golem/selector.ts` is what refuses it.
import { existsSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { pathToFileURL } from "node:url";

import { SELECTOR_MARGIN, SELECTOR_VERSION, cellKey, choose, scoreIn } from "../src/golem/selector.ts";
import { readRows } from "./tournament.mjs";

/** A win is a point, a draw half of one; the same scale `summarize` rates on. */
export function pointsFor(row, side) {
  return row.winner === side ? 1 : row.winner === null ? 0.5 : 0;
}

const add = (into, key, points) => {
  const cell = into[key] ?? (into[key] = { n: 0, points: 0 });
  cell.n += 1;
  cell.points += points;
};

/**
 * Count every side of every row into the three levels.
 *
 * A row whose side has no `arm` is skipped and counted: the column arrived in Session 07 of the
 * matchup set and a file older than that has bouts but no classes to key them by.
 */
export function fitSelector(rows, { shrink = 32, minds = null, seed = 0, date = "" } = {}) {
  const marginal = {};
  const byClass = {};
  const cells = {};
  const found = [];
  let counted = 0;
  let skipped = 0;
  for (const row of rows) {
    for (const [me, them] of [["left", "right"], ["right", "left"]]) {
      const mind = row[me].policy;
      if (minds !== null && !minds.includes(mind)) continue;
      const mine = row[me].arm;
      const theirs = row[them].arm;
      if (typeof mine !== "string" || typeof theirs !== "string") { skipped += 1; continue; }
      if (!found.includes(mind)) found.push(mind);
      const points = pointsFor(row, me);
      add(marginal, mind, points);
      add(byClass, `${mine}|${mind}`, points);
      add(cells, `${cellKey(mine, theirs)}|${mind}`, points);
      counted += 1;
    }
  }
  return {
    table: {
      version: SELECTOR_VERSION, seed, date, bouts: rows.length, shrink,
      minds: minds === null ? found : minds.filter((m) => found.includes(m)),
      marginal, byClass, cells,
    },
    counted, skipped,
  };
}

/** Every ordered class pair the rows visited, most-fought first, with what `choose` does in it. */
export function cellReport(table) {
  const pairs = new Map();
  for (const key of Object.keys(table.cells)) {
    const [mine, theirs] = key.split("|");
    const cell = table.cells[key];
    const at = `${mine}|${theirs}`;
    pairs.set(at, (pairs.get(at) ?? 0) + cell.n);
  }
  const rows = [];
  for (const [at, bouts] of pairs) {
    const [mine, theirs] = at.split("|");
    const decision = choose(table, mine, theirs);
    const ranked = table.minds
      .map((mind) => ({ mind, score: scoreIn(table, mind, mine, theirs), n: table.cells[`${at}|${mind}`]?.n ?? 0 }))
      .sort((a, b) => b.score - a.score);
    rows.push({ cell: at, mine, theirs, bouts, decision, ranked });
  }
  rows.sort((a, b) => b.bouts - a.bouts);
  return rows;
}

/** The module text: a header that says where the numbers came from, then the literal. */
export function renderSelectorModule(table, { sources }) {
  const round = (value) => Math.round(value * 100) / 100;
  const level = (part) => {
    const out = {};
    for (const [key, cell] of Object.entries(part)) out[key] = { n: cell.n, points: round(cell.points) };
    return out;
  };
  const literal = JSON.stringify({
    ...table,
    marginal: level(table.marginal), byClass: level(table.byClass), cells: level(table.cells),
  });
  return [
    "// GENERATED by scripts/fit-selector.mjs -- do not edit; regenerate.",
    "//",
    `// Selector table, version ${table.version}, fitted ${table.date} from seed ${table.seed}:`,
    `// ${table.bouts} bouts over ${table.minds.length} candidates, shrinkage ${table.shrink} bouts a level,`,
    `// a cell's winner playing only ${SELECTOR_MARGIN} points a bout above the marginal winner.`,
    `// Sources: ${sources.join(", ")}.`,
    "//",
    "// What the numbers are, and how the mind reads them, is in src/golem/selector.ts; a build",
    "// that reads another version refuses this file by name rather than reinterpreting it.",
    "import type { SelectorTable } from \"./selector.ts\";",
    "",
    `export const SELECTOR_TABLE: SelectorTable = ${literal};`,
    "",
  ].join("\n");
}

const isMain = process.argv[1] !== undefined
  && pathToFileURL(resolve(process.argv[1])).href === import.meta.url;

if (isMain) {
  const argv = process.argv.slice(2);
  const flag = (name, fallback) => {
    const at = argv.indexOf(`--${name}`);
    return at >= 0 && argv[at + 1] !== undefined ? argv[at + 1] : fallback;
  };
  const sources = flag("in", "").split(",").map((s) => s.trim()).filter(Boolean);
  if (sources.length === 0) throw new Error("--in wants one or more tournament row files");
  for (const source of sources) if (!existsSync(source)) throw new Error(`${source} does not exist`);
  const out = resolve(flag("out", "src/golem/selector-table.ts"));
  const shrink = Number(flag("shrink", 32));
  const named = flag("minds", "");
  const minds = named === "" ? null : named.split(",").map((s) => s.trim()).filter(Boolean);
  const rows = [];
  let seed = 0;
  for (const source of sources) {
    const read = readRows(source);
    if (seed === 0) seed = read.header.seed;
    for (const row of read.rows) rows.push(row);
  }
  const { table, counted, skipped } = fitSelector(rows, {
    shrink, minds, seed, date: new Date().toISOString().slice(0, 10),
  });
  if (table.minds.length === 0) throw new Error("no candidate sides in the rows; is `arm` on them?");
  const report = cellReport(table);
  if (argv.includes("--report")) {
    const pad = (s, w) => String(s).padEnd(w);
    console.log(`${pad("cell", 34)}  bouts  ${pad("plays", 18)}  ${pad("cell best", 18)}  score  marginal  edge`);
    for (const row of report) {
      const d = row.decision;
      console.log(
        `${pad(row.cell, 34)}  ${String(row.bouts).padStart(5)}  ${pad(d.mind, 18)}  ${pad(d.best, 18)}  `
        + `${d.bestScore.toFixed(3)}  ${d.marginalScore.toFixed(3)}     ${(d.bestScore - d.marginalScore).toFixed(3)}`);
    }
  }
  const text = renderSelectorModule(table, { sources: sources.map((s) => s.replace(/\\/g, "/")) });
  writeFileSync(out, text);
  const moved = report.filter((row) => row.decision.mind !== row.decision.marginal);
  const marginalName = report.length > 0 ? report[0].decision.marginal : "none";
  console.log(`${counted} sides from ${rows.length} bouts (${skipped} without an arm class), ${table.minds.length} candidates`);
  console.log(`marginal winner ${marginalName}; ${moved.length} of ${report.length} cells play something else`);
  for (const row of moved) console.log(`  ${row.cell}: ${row.decision.mind} (${row.bouts} bouts, +${(row.decision.bestScore - row.decision.marginalScore).toFixed(3)})`);
  console.log(`${(text.length / 1024).toFixed(0)} KB -> ${out}`);
}
