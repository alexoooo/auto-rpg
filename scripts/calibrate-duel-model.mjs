// Fit the duel model's tables from tournament rows that carry an exchange log, and write them
// out as the checked-in module `src/golem/duel-model-tables.ts`. Session 06 of the matchup set.
//
//   node scripts/calibrate-duel-model.mjs --in a.jsonl[,b.jsonl] [--out src/golem/duel-model-tables.ts]
//                                          [--shrink 4] [--prune 10]
//
// The rows come from `node scripts/tournament.mjs ... --exchanges`; a row without an exchange
// log is skipped and counted. `--prune N` drops transition successors seen fewer than N times,
// which is what keeps the module small enough to check in and ship: a successor seen once in
// forty thousand windows is noise with a name. At the default of ten, the 2026-09-07 calibration
// (217,569 windows) wrote 130 KB against 208 KB at two, with the same 687 outcome cells. Outcome
// cells are never pruned, because a cell with one record still shrinks correctly toward its
// parent.
//
// What this writes is a plain object literal, the tables as `fitDuelModel` returns them, with
// the seed, the date, the bout and record counts and the shrinkage in its header, so that the
// module can be regenerated to the byte from the same rows and refused by version by any build
// that reads a different one. The file is generated; edit this script, not it.
import { existsSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { pathToFileURL } from "node:url";

import { DUEL_MODEL_VERSION, fitDuelModel } from "../src/golem/duel-model.ts";
import { EXCHANGE_WINDOW_SECONDS, readRows } from "./tournament.mjs";

/** Read the exchange records out of one or more row files. */
export function collectRecords(paths) {
  const records = [];
  let bouts = 0;
  let skipped = 0;
  let seed = null;
  for (const path of paths) {
    const { header, rows } = readRows(path);
    if (seed === null) seed = header.seed;
    for (const row of rows) {
      const log = row.exchanges;
      if (!log) { skipped += 1; continue; }
      let any = false;
      for (const side of ["left", "right"]) {
        if (!log[side]) continue;
        any = true;
        for (const record of log[side]) records.push(record);
      }
      if (any) bouts += 1; else skipped += 1;
    }
  }
  return { records, bouts, skipped, seed: seed ?? 0 };
}

/** Drop the successors of a transition table seen fewer than `prune` times. */
export function pruneTransitions(table, prune) {
  const out = {};
  for (const [key, row] of Object.entries(table)) {
    const kept = {};
    for (const [next, n] of Object.entries(row)) if (n >= prune) kept[next] = n;
    if (Object.keys(kept).length > 0) out[key] = kept;
  }
  return out;
}

/**
 * How a rendered module names itself: which script wrote it, what the tables are called, and
 * which type and constant the file declares.
 *
 * Session 09 made this an argument because the style model's tables are the same literal under
 * different names, and the alternative -- rendering the duel module and then running six string
 * replacements over the text -- is a renderer whose output depends on the *spelling* of its own
 * header, which nothing would catch when a word in it changed.
 */
export const DUEL_NAMING = Object.freeze({
  script: "scripts/calibrate-duel-model.mjs",
  title: "Duel model tables",
  source: "src/golem/duel-model.ts",
  module: "./duel-model.ts",
  type: "DuelModelTables",
  constant: "DUEL_MODEL_TABLES",
});

/** The module text: a header that says where the numbers came from, then the literal. */
export function renderTablesModule(tables, { sources, prune, naming = DUEL_NAMING }) {
  const round = (value) => Math.round(value * 1000) / 1000;
  const cells = (table) => {
    const out = {};
    for (const [key, c] of Object.entries(table)) out[key] = { n: c.n, dealt: round(c.dealt), taken: round(c.taken) };
    return out;
  };
  const literal = JSON.stringify({
    ...tables,
    outcomes: cells(tables.outcomes),
    outcomesCoarse: cells(tables.outcomesCoarse),
    outcomesOption: cells(tables.outcomesOption),
  });
  return [
    `// GENERATED by ${naming.script} -- do not edit; regenerate.`,
    "//",
    `// ${naming.title}, version ${tables.version}, fitted ${tables.date} from seed ${tables.seed}:`,
    `// ${tables.bouts} bouts with an exchange log, ${tables.records} option windows of at most`,
    `// ${tables.windowSeconds} s, shrinkage ${tables.shrink}, transition successors seen under ${prune} times dropped.`,
    `// Sources: ${sources.join(", ")}.`,
    "//",
    `// What the numbers are, and how a mind reads them, is in ${naming.source}; a build`,
    "// that reads another version refuses this file by name rather than reinterpreting it.",
    `import type { ${naming.type} } from "${naming.module}";`,
    "",
    `export const ${naming.constant}: ${naming.type} = ${literal};`,
    "",
  ].join("\n");
}

const isMain = process.argv[1] !== undefined
  && pathToFileURL(resolve(process.argv[1])).href === import.meta.url;

if (isMain) {
  const argv = process.argv.slice(2);
  const flag = (name, fallback) => {
    const at = argv.indexOf(`--${name}`);
    return at >= 0 && argv[at + 1] !== undefined ? argv[at + 1] : fallback;
  };
  const sources = flag("in", "").split(",").map((s) => s.trim()).filter(Boolean);
  if (sources.length === 0) throw new Error("--in wants one or more row files with an exchange log");
  for (const source of sources) if (!existsSync(source)) throw new Error(`${source} does not exist`);
  const out = resolve(flag("out", "src/golem/duel-model-tables.ts"));
  const shrink = Number(flag("shrink", 4));
  const prune = Number(flag("prune", 10));
  const { records, bouts, skipped, seed } = collectRecords(sources);
  if (records.length === 0) throw new Error("no exchange records in the rows; run the tournament with --exchanges");
  const tables = fitDuelModel(records, {
    seed, date: new Date().toISOString().slice(0, 10), bouts, windowSeconds: EXCHANGE_WINDOW_SECONDS, shrink,
  });
  tables.transitions = pruneTransitions(tables.transitions, prune);
  tables.transitionsCoarse = pruneTransitions(tables.transitionsCoarse, prune);
  const text = renderTablesModule(tables, { sources: sources.map((s) => s.replace(/\\/g, "/")), prune });
  writeFileSync(out, text);
  const options = {};
  for (const r of records) options[r.option] = (options[r.option] ?? 0) + 1;
  console.log(`${records.length} records from ${bouts} bouts (${skipped} rows without a log), version ${DUEL_MODEL_VERSION}`);
  console.log(`options: ${Object.entries(options).map(([k, v]) => `${k} ${v}`).join(", ")}`);
  console.log(`${Object.keys(tables.outcomes).length} outcome cells, ${Object.keys(tables.transitions).length} transition rows, ${(text.length / 1024).toFixed(0)} KB -> ${out}`);
}
